import {
  RulegateError,
  importedRule,
  slugForId,
  stripMarker,
  type JsonValue,
  type RuleDocument,
} from '@rulegate/adapter-kit';

/**
 * Claude Code's path-scoped rules: `.claude/rules/<slug>.md`, YAML frontmatter holding one
 * key, `paths`, then Markdown.
 *
 * Three facts from the vendor page shape everything here. `paths` is the only field Claude
 * Code reads, and it strips the frontmatter before the rule loads, so a description only
 * reaches the model as a heading in the body. `paths` accepts a YAML list or a
 * comma-separated string, and brace expansion (`src/*.{ts,tsx}`) puts commas inside a
 * single glob, so only the list form is safe to emit. And frontmatter that does not parse
 * is ignored without an error — the rule loads repo-wide — so every glob is double-quoted:
 * a bare `*` opens a YAML alias, and the first unquoted `- **\/*.ts` list item would
 * silently unscope the rule it was meant to scope.
 *
 * Source: https://code.claude.com/docs/en/memory (retrieved 2026-09-26, Claude Code 2.1.283).
 */
export const RULES_DIR = '.claude/rules';

export function rulePath(rule: RuleDocument): string {
  return `${RULES_DIR}/${slugForId(rule.id)}.md`;
}

/** A YAML double-quoted scalar escapes exactly two characters that can appear in a glob. */
function quote(glob: string): string {
  return `"${glob.replace(/\\/g, '\\\\').replace(/"/g, '\\"')}"`;
}

export function renderPathsFrontmatter(globs: readonly string[]): string {
  return ['---', 'paths:', ...globs.map((glob) => `  - ${quote(glob)}`), '---'].join('\n');
}

// Commas are legal here, unlike in Cursor's and Copilot's single-string fields, because
// every glob is its own list item. A line break is not: it would end the scalar mid-glob.
// eslint-disable-next-line no-control-regex
const CONTROL = /[\u0000-\u001f\u007f]/;

export function assertRenderable(rule: RuleDocument): void {
  for (const glob of rule.frontmatter.globs) {
    if (CONTROL.test(glob)) {
      throw new RulegateError({
        code: 'E_FRONTMATTER_INVALID',
        message: `glob ${JSON.stringify(glob)} in rule \`${rule.id}\` contains a control character, which Claude Code's \`paths:\` frontmatter cannot carry`,
        source: rule.source,
        hint: 'remove the line break or tab from the glob',
      });
    }
  }
}

export function renderScopedRule(rule: RuleDocument, section: string, marker: boolean): string {
  assertRenderable(rule);
  // The marker follows the frontmatter rather than leading the file: YAML frontmatter must
  // occupy the first bytes, so a leading HTML comment would stop it being frontmatter.
  const head = renderPathsFrontmatter(rule.frontmatter.globs);
  return marker
    ? `${head}\n<!-- generated by rulegate; edit .rulegate/ instead -->\n\n${section}`
    : `${head}\n${section}`;
}

export interface ParsedRuleFile {
  readonly description?: string;
  readonly paths: readonly string[];
  /** Keys the frontmatter carried that canonical has no field for, preserved verbatim. */
  readonly unknown: Readonly<Record<string, JsonValue>>;
  /** Everything after the frontmatter, or the whole file when there is none Claude reads. */
  readonly remainder: string;
}

/**
 * One `.claude/rules` file -> exactly one canonical rule, the inverse of `renderScopedRule`.
 *
 * Not `importConcatenated`, which splits at every `## ` heading: a file holds one rule by
 * construction, so a body with its own `## Server components` would come back as two
 * rules, and `sync --import` would then refuse every hand-edit of the file for having more
 * sections than rules produced it. Here the marker, and only the marker, says the first
 * heading is ours — the description `write` moved into the body. A file whose frontmatter
 * did not parse has `---` as its first line, so it is never read as marked and its whole
 * text stays one body.
 */
export function importRuleFile(
  file: string,
  id: string,
  parsed: ParsedRuleFile,
): RuleDocument | undefined {
  const stripped = stripMarker(parsed.remainder);
  let body = stripped;
  let description = parsed.description;
  if (stripped !== parsed.remainder) {
    const heading = /^## +(.*)(?:\n|$)/.exec(stripped);
    const title = heading?.[1]?.trim() ?? '';
    if (heading !== null && title !== '') {
      description = title;
      body = stripped.slice(heading[0].length).replace(/^\n+/, '');
    }
  }
  body = body.replace(/\n+$/, '');
  if (body.trim() === '' && description === undefined) return undefined;
  return importedRule({
    id,
    body: body === '' ? '' : `${body}\n`,
    ...(description === undefined ? {} : { description }),
    globs: parsed.paths,
    unknown: parsed.unknown,
    source: { file, line: 1 },
  });
}

type Value = string | Value[] | { [key: string]: Value };

const KEY_LINE = /^([^:\s#-][^:]*):(?:[ \t]+(.*))?$/;
const ITEM_LINE = /^-(?:[ \t]+(.*))?$/;
const BLOCK_SCALAR = /^([|>])([-+]?)\d?$/;
/** The values Claude Code's retry double-quotes. */
const REPAIRED = /[{}[\]*&#!|>%@`]|: /;

// Canonical's own frontmatter keys. Claude Code ignores all three, and carrying one into
// `unknown` would have it re-emitted under a name canonical does read — a stray `globs:`
// in a Claude rule would rescope the rule for every other tool.
const RESERVED = new Set(['globs', 'tools', 'order']);

/**
 * `.claude/rules/*.md` -> its parts, line-wise rather than with the `yaml` package because
 * an adapter's dependency footprint is part of its contract.
 *
 * It covers the YAML people actually hand-write in frontmatter — block and flow lists,
 * nested mappings, block scalars, quoted keys, trailing `#` comments — because every
 * shape it cannot read falls back to repo-wide, and on *valid* YAML that fallback is a
 * silent unscoping Claude Code itself would not do. What remains unread (flow mappings,
 * anchors, a list of mappings) falls back the way Claude Code does on frontmatter that is
 * not YAML: the rule is repo-wide and its whole text — frontmatter included — becomes the
 * body, so the import loses nothing a user wrote.
 *
 * "Not YAML" is Claude Code's line, not the YAML spec's. When a strict parse fails, Claude
 * Code 2.1.283 retries once after two repairs: every top-level `key: value` whose bare
 * value holds a YAML indicator or `: ` is double-quoted whole, and each leading tab becomes
 * two spaces (`OMt` and its helper in the shipped bundle, read 2026-09-26). So
 * `paths: *.tsx` and a tab-indented list are scoped there, and are scoped here; the same
 * shapes one level down are not repaired there, and fall back here.
 */
export function parseRuleFile(contents: string): ParsedRuleFile {
  const text = contents.replace(/^\uFEFF/, '').replace(/\r\n?/g, '\n');
  const whole: ParsedRuleFile = { paths: [], unknown: {}, remainder: text };

  const lines = text.split('\n');
  if ((lines[0] ?? '').trim() !== '---') return whole;
  const close = lines.findIndex((line, i) => i > 0 && ['---', '...'].includes(line.trim()));
  if (close === -1) return whole;

  const block = lines
    .slice(1, close)
    .map((line) => line.replace(/^\t+/, (t) => '  '.repeat(t.length)));
  // A tab left after the repair is indentation no YAML parser reads.
  if (block.some((line) => !isSkippable(line) && /^ *\t/.test(line))) return whole;
  const mapping = parseMapping(block, 0, 0);
  if (mapping === undefined || mapping.next !== block.length) return whole;

  let description: string | undefined;
  let paths: string[] = [];
  const unknown: Record<string, JsonValue> = {};

  for (const [key, value] of mapping.entries) {
    if (key === 'paths') {
      const globs =
        typeof value === 'string' ? splitOutside(value).map((part) => part.trim()) : value;
      if (!Array.isArray(globs) || !globs.every((glob) => typeof glob === 'string')) {
        return whole;
      }
      paths = globs.filter((glob) => glob !== '');
    } else if (key === 'description') {
      if (typeof value !== 'string') return whole;
      if (value.trim() !== '') description = value.trim();
    } else if (!RESERVED.has(key)) {
      unknown[key] = value;
    }
  }

  return {
    ...(description === undefined ? {} : { description }),
    paths,
    unknown,
    remainder: lines
      .slice(close + 1)
      .join('\n')
      .replace(/^\n+/, ''),
  };
}

function indentOf(line: string): number {
  return line.length - line.trimStart().length;
}

function isSkippable(line: string): boolean {
  const trimmed = line.trim();
  return trimmed === '' || trimmed.startsWith('#');
}

function nextContent(lines: readonly string[], from: number): number {
  let i = from;
  while (i < lines.length && isSkippable(lines[i] ?? '')) i += 1;
  return i;
}

interface Parsed<T> {
  readonly value: T;
  readonly next: number;
}

/** A block mapping whose keys sit at exactly `indent`; it ends at the first shallower line. */
function parseMapping(
  lines: readonly string[],
  start: number,
  indent: number,
): { entries: [string, Value][]; next: number } | undefined {
  const entries: [string, Value][] = [];
  let i = nextContent(lines, start);
  while (i < lines.length) {
    const line = lines[i] ?? '';
    const own = indentOf(line);
    if (own < indent) break;
    if (own > indent) return undefined;

    const pair = splitKey(line.slice(own));
    if (pair === undefined) return undefined;
    // Claude Code's retry quotes only top-level lines with a plain `[a-zA-Z_-]` key.
    const repairable = own === 0 && pair.bare && /^[a-zA-Z_-]+$/.test(pair.key);
    const value = parseValue(lines, i, own, pair.rest, repairable);
    if (value === undefined) return undefined;
    entries.push([pair.key, value.value]);
    i = nextContent(lines, value.next);
  }
  return { entries, next: i };
}

/** `key: rest`, with the key bare or quoted — `"paths":` is the same key as `paths:`. */
function splitKey(text: string): { key: string; rest: string; bare: boolean } | undefined {
  if (text.startsWith('"') || text.startsWith("'")) {
    const end = closingQuote(text);
    if (end === -1) return undefined;
    const after = text.slice(end + 1);
    const match = /^[ \t]*:(?:[ \t]+(.*))?$/.exec(after);
    const key = unquote(text.slice(0, end + 1));
    if (match === null || key === undefined) return undefined;
    return { key, rest: match[1] ?? '', bare: false };
  }
  const match = KEY_LINE.exec(text);
  if (match === null) return undefined;
  return { key: (match[1] ?? '').trim(), rest: match[2] ?? '', bare: true };
}

/** The value of the key on line `at` (indented `indent`), whose inline text is `inline`. */
function parseValue(
  lines: readonly string[],
  at: number,
  indent: number,
  inline: string,
  repairable = false,
): Parsed<Value> | undefined {
  const raw = stripComment(inline).trim();

  const scalar = BLOCK_SCALAR.exec(raw);
  if (scalar !== null) return parseBlockScalar(lines, at + 1, indent, scalar);

  if (raw !== '') {
    const value = raw.startsWith('[') ? parseFlowList(raw) : unquote(raw);
    if (value !== undefined) return { value, next: at + 1 };
    // Claude Code's retry: the raw text, comment and all, as one string.
    const text = inline.trimEnd();
    // A balanced flow collection is valid YAML the retry never runs on: Claude Code reads it
    // as a structure `paths` cannot use, and the rule is repo-wide there too.
    const flow = /^\{.*\}$|^\[.*\]$/.test(text);
    if (repairable && !flow && !/^["']/.test(text) && REPAIRED.test(text)) {
      return { value: text, next: at + 1 };
    }
    return undefined;
  }

  // Nothing inline: the value is whatever is indented beneath the key — a list (YAML also
  // allows its dashes level with the key), a nested mapping, or nothing at all.
  const j = nextContent(lines, at + 1);
  const below = lines[j];
  if (below === undefined) return { value: '', next: at + 1 };
  const own = indentOf(below);
  if (ITEM_LINE.test(below.trimStart()) && own >= indent) return parseList(lines, j, own);
  if (own > indent) {
    const mapping = parseMapping(lines, j, own);
    if (mapping === undefined) return undefined;
    return { value: Object.fromEntries(mapping.entries), next: mapping.next };
  }
  return { value: '', next: at + 1 };
}

function parseList(
  lines: readonly string[],
  start: number,
  indent: number,
): Parsed<Value> | undefined {
  const items: Value[] = [];
  let i = start;
  while (i < lines.length) {
    const line = lines[i] ?? '';
    if (indentOf(line) !== indent) break;
    const item = ITEM_LINE.exec(line.trimStart());
    if (item === null) break;
    // A list of mappings (`- key: value`) is not a shape `paths` or anything here takes.
    const value = unquote(stripComment(item[1] ?? '').trim());
    if (value === undefined || splitKey(item[1] ?? '') !== undefined) return undefined;
    items.push(value);
    i = nextContent(lines, i + 1);
  }
  return { value: items, next: i };
}

/** `|` keeps line breaks, `>` folds them into spaces; `-` strips the final newline. */
function parseBlockScalar(
  lines: readonly string[],
  start: number,
  indent: number,
  header: RegExpExecArray,
): Parsed<Value> {
  const body: string[] = [];
  let i = start;
  while (i < lines.length) {
    const line = lines[i] ?? '';
    if (line.trim() !== '' && indentOf(line) <= indent) break;
    body.push(line);
    i += 1;
  }
  while (body.length > 0 && (body[body.length - 1] ?? '').trim() === '') body.pop();
  if (body.length === 0) return { value: '', next: i };
  const content = Math.min(...body.filter((l) => l.trim() !== '').map(indentOf));
  const stripped = body.map((line) => line.slice(content));
  let text = '';
  if (header[1] === '|') text = stripped.join('\n');
  else {
    for (const line of stripped) {
      if (line.trim() === '') text += '\n';
      else text += (text === '' || text.endsWith('\n') ? '' : ' ') + line;
    }
  }
  return { value: header[2] === '-' ? text : `${text}\n`, next: i };
}

function parseFlowList(raw: string): Value | undefined {
  if (!raw.endsWith(']')) return undefined;
  const items: string[] = [];
  for (const part of splitOutside(raw.slice(1, -1))) {
    const value = unquote(part.trim());
    if (value === undefined) return undefined;
    items.push(value);
  }
  return items;
}

/**
 * Drop a trailing `# comment`. YAML only starts one at a `#` preceded by whitespace and
 * outside quotes, so `src/#legacy/**` keeps its `#` and `"a # b"` keeps its text.
 */
function stripComment(value: string): string {
  let quoteChar: string | undefined;
  for (let i = 0; i < value.length; i += 1) {
    const ch = value[i];
    if (quoteChar !== undefined) {
      if (ch === '\\' && quoteChar === '"') i += 1;
      else if (ch === quoteChar) quoteChar = undefined;
      continue;
    }
    const before = value.slice(0, i).trimEnd();
    if ((ch === '"' || ch === "'") && (before === '' || /[[,]$/.test(before))) quoteChar = ch;
    else if (ch === '#' && (i === 0 || /\s/.test(value[i - 1] ?? ''))) return value.slice(0, i);
  }
  return value;
}

/** Index of the quote closing the quoted scalar that opens `value`, or -1. */
function closingQuote(value: string): number {
  const open = value[0];
  for (let i = 1; i < value.length; i += 1) {
    const ch = value[i];
    if (open === '"' && ch === '\\') i += 1;
    else if (ch === open) {
      if (open === "'" && value[i + 1] === "'") i += 1;
      else return i;
    }
  }
  return -1;
}

/**
 * Split on commas that separate patterns, not the ones inside a brace group or a quoted
 * item: `src/*.{ts,tsx}, lib/**` is two patterns, not three.
 */
function splitOutside(value: string): string[] {
  const parts: string[] = [];
  let depth = 0;
  let quoteChar: string | undefined;
  let start = 0;
  for (let i = 0; i < value.length; i += 1) {
    const ch = value[i];
    if (quoteChar !== undefined) {
      if (ch === '\\' && quoteChar === '"') i += 1;
      else if (ch === quoteChar) quoteChar = undefined;
    } else if (ch === '"' || ch === "'") quoteChar = ch;
    else if (ch === '{') depth += 1;
    else if (ch === '}') depth = Math.max(0, depth - 1);
    else if (ch === ',' && depth === 0) {
      parts.push(value.slice(start, i));
      start = i + 1;
    }
  }
  parts.push(value.slice(start));
  return parts.filter((part) => part.trim() !== '');
}

/**
 * The inverse of `quote`, plus single-quoted and bare scalars, with YAML's escapes decoded
 * rather than dropped. `undefined` means strict YAML refuses the value — an unterminated
 * quote, an unknown escape, a bare value opening with an indicator or holding `: ` — and
 * `parseValue` then decides whether Claude Code's retry would have rescued it.
 */
function unquote(value: string): string | undefined {
  if (value.startsWith('"')) {
    let out = '';
    for (let i = 1; i < value.length; i += 1) {
      const ch = value[i] ?? '';
      if (ch === '"') return i === value.length - 1 ? out : undefined;
      if (ch === '\\') {
        const escape = decodeEscape(value, i + 1);
        if (escape === undefined) return undefined;
        out += escape.text;
        i = escape.end;
      } else out += ch;
    }
    return undefined;
  }
  if (value.startsWith("'")) {
    if (value.length < 2 || !value.endsWith("'")) return undefined;
    return value.slice(1, -1).replace(/''/g, "'");
  }
  // `a: b` is a mapping inside a scalar, which YAML refuses.
  if (/^[*&!|>%@`[{]/.test(value) || /: |:$/.test(value)) return undefined;
  return value;
}

const ESCAPES: Readonly<Record<string, string>> = {
  '0': '\0',
  a: '\x07',
  b: '\b',
  t: '\t',
  '\t': '\t',
  n: '\n',
  v: '\v',
  f: '\f',
  r: '\r',
  e: '\x1b',
  ' ': ' ',
  '"': '"',
  '/': '/',
  '\\': '\\',
  N: '\u0085',
  _: '\u00a0',
  L: '\u2028',
  P: '\u2029',
};

/** A YAML double-quoted escape starting at `at` (just past the backslash). */
function decodeEscape(value: string, at: number): { text: string; end: number } | undefined {
  const ch = value[at] ?? '';
  const simple = ESCAPES[ch];
  if (simple !== undefined) return { text: simple, end: at };
  const width = ch === 'x' ? 2 : ch === 'u' ? 4 : ch === 'U' ? 8 : 0;
  const hex = value.slice(at + 1, at + 1 + width);
  if (width === 0 || !new RegExp(`^[0-9a-fA-F]{${String(width)}}$`).test(hex)) return undefined;
  const code = Number.parseInt(hex, 16);
  if (code > 0x10ffff) return undefined;
  return { text: String.fromCodePoint(code), end: at + width };
}
