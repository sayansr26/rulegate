import { describe, expect, it } from 'vitest';
import {
  expectContentCovered,
  expectImportMatch,
  importContextFor,
  importFixture,
  readInput,
} from '@rulegate/adapter-kit/testing';
import { claudeCode } from '../src/index.js';
import { parseRuleFile } from '../src/rules.js';

describe('claude-code read() (T017)', () => {
  it('imports the fixture repo into the expected canonical rules', async () => {
    await expectImportMatch('claude-code', claudeCode);
  });

  it('loses no user content', async () => {
    await expectContentCovered('claude-code', claudeCode, [
      'CLAUDE.md',
      '.claude/rules/backend/db.md',
      '.claude/rules/security.md',
    ]);
  });

  // The harness's coverage check does not read YAML block-list items (`  - "glob"`), so
  // the two block-list files are covered here: every glob in globs, every other line in
  // a body, a description or an unknown value.
  it('loses no user content from block-list rule files (T110)', async () => {
    const dir = importFixture('claude-code').input;
    const rules = (await claudeCode.read(importContextFor(dir))).rules ?? [];
    const input = await readInput(dir);

    for (const file of ['.claude/rules/30-components.md', '.claude/rules/api.md']) {
      const contents = input.get(file) ?? '';
      const imported = rules.find((r) => r.source.file === file);
      expect(imported, file).toBeDefined();
      expect(imported?.frontmatter.globs).toEqual(parseRuleFile(contents).paths);

      const text = [
        imported?.body ?? '',
        imported?.frontmatter.description ?? '',
        ...Object.values(imported?.frontmatter.unknown ?? {}).map(String),
      ].join('\n');
      for (const line of parseRuleFile(contents).remainder.split('\n')) {
        const trimmed = line.trim().replace(/^#+\s*/, '');
        if (trimmed === '' || trimmed.includes('generated by rulegate')) continue;
        expect(text, `${file}: ${line}`).toContain(trimmed);
      }
    }
  });
});
