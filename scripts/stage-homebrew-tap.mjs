#!/usr/bin/env node
// Lay out the Homebrew tap, sayansr26/homebrew-rulegate, for one published version (T061).
//
//   node scripts/stage-homebrew-tap.mjs <dir> <version> <sha256>           write into <dir>
//   node scripts/stage-homebrew-tap.mjs <dir> <version> <sha256> --check   exit 1 if stale
//
// The formula installs the exact tarball npm serves for <version>, pinned by <sha256>, which
// the release workflow computes from the registry's bytes after `verify-published.mjs` has
// confirmed the version is live and signed — so the formula can never name a version npm does
// not have. This script is the one definition of what the tap contains, so every release
// refreshes it the same way. It touches no git and no network: fetching the tarball and pushing
// the tap are the workflow's.
import { mkdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';

const [target, version, sha256, ...flags] = process.argv.slice(2);
const check = flags.includes('--check');
if (!target || !version || !sha256) {
  process.stderr.write('usage: stage-homebrew-tap.mjs <dir> <version> <sha256> [--check]\n');
  process.exit(2);
}
// Refused rather than written: either would produce a formula `brew` rejects, or one that
// installs something other than what was verified.
if (!/^\d+\.\d+\.\d+(?:-[0-9A-Za-z.-]+)?$/.test(version)) {
  process.stderr.write(`not a version: ${version}\n`);
  process.exit(2);
}
if (!/^[0-9a-f]{64}$/.test(sha256)) {
  process.stderr.write(`not a sha256: ${sha256}\n`);
  process.exit(2);
}

const root = new URL('..', import.meta.url).pathname;
const cli = JSON.parse(readFileSync(join(root, 'packages/cli/package.json'), 'utf8'));

const files = renderTap({ version, sha256, license: cli.license });

let stale = 0;
for (const [path, contents] of files) {
  const abs = join(target, path);
  const current = existsSync(abs) ? readFileSync(abs, 'utf8') : undefined;
  if (current === contents) continue;
  if (check) {
    process.stderr.write(`${path} is out of date\n`);
    stale += 1;
    continue;
  }
  mkdirSync(dirname(abs), { recursive: true });
  writeFileSync(abs, contents);
  process.stdout.write(`wrote ${path}\n`);
}
if (check && stale > 0) process.exit(1);
if (check) process.stdout.write(`${target} is up to date for ${version}\n`);

/**
 * The tap's files, as a sorted list of [path, contents].
 *
 * `desc` is written here rather than taken from package.json: `brew audit` wants at most 80
 * characters, no leading article and no final period, and the npm description is two
 * sentences. The formula is Homebrew's standard shape for an npm CLI — `std_npm_args` installs
 * the tarball and its dependencies into `libexec` — and its test runs the launch demo, not just
 * `--version`, because a CLI that prints its version and fails its first command is the
 * failure a Homebrew user would actually meet.
 */
function renderTap({ version, sha256, license }) {
  const formula = `# Generated by scripts/stage-homebrew-tap.mjs in sayansr26/rulegate on each release.
# Edit that script, not this file: the next release overwrites it.
class Rulegate < Formula
  desc "Sync, verify, and inspect config for AI coding agents"
  homepage "https://github.com/sayansr26/rulegate"
  url "https://registry.npmjs.org/rulegate/-/rulegate-${version}.tgz"
  sha256 "${sha256}"
  license "${license}"

  depends_on "node"

  def install
    system "npm", "install", *std_npm_args
    bin.install_symlink libexec.glob("bin/*")
  end

  test do
    assert_equal version.to_s, shell_output("#{bin}/rulegate --version").strip

    system "git", "init", "-q"
    (testpath/"CLAUDE.md").write "# Project\\n\\nUse small modules.\\n"
    system bin/"rulegate", "init", "--yes"
    system bin/"rulegate", "check"
  end
end
`;
  const readme = `# homebrew-rulegate

The Homebrew tap for [Rulegate](https://github.com/sayansr26/rulegate): one source of truth for
your AI coding agents.

\`\`\`sh
brew install sayansr26/rulegate/rulegate
\`\`\`

\`Formula/rulegate.rb\` is generated by \`scripts/stage-homebrew-tap.mjs\` in the main repository
and updated by its release workflow each time a version reaches npm, so it installs exactly the
tarball npm serves. Issues and changes belong in
[sayansr26/rulegate](https://github.com/sayansr26/rulegate).
`;
  return [
    ['Formula/rulegate.rb', formula],
    ['README.md', readme],
  ];
}
